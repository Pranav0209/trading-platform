BEGIN;

DROP TABLE IF EXISTS pnl CASCADE;
DROP TABLE IF EXISTS watchlist_instruments CASCADE;
DROP TABLE IF EXISTS watchlists CASCADE;
DROP TABLE IF EXISTS holdings CASCADE;
DROP TABLE IF EXISTS positions CASCADE;
DROP TABLE IF EXISTS orders CASCADE;
DROP TABLE IF EXISTS instruments CASCADE;
DROP TABLE IF EXISTS accounts CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
    user_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    email VARCHAR(255) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_users_status CHECK (status IN ('ACTIVE','BLOCKED','INACTIVE'))
);

CREATE TABLE accounts (
    account_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    account_number VARCHAR(30) NOT NULL UNIQUE,
    cash_balance NUMERIC(20,2) NOT NULL DEFAULT 0,
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_accounts_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE RESTRICT,
    CONSTRAINT chk_accounts_cash CHECK (cash_balance >= 0),
    CONSTRAINT chk_accounts_version CHECK (version >= 0),
    CONSTRAINT chk_accounts_status CHECK (status IN ('ACTIVE','SUSPENDED','CLOSED'))
);
CREATE INDEX idx_accounts_user_id ON accounts(user_id);

CREATE TABLE instruments (
    instrument_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    symbol VARCHAR(30) NOT NULL,
    isin VARCHAR(20) UNIQUE,
    company_name VARCHAR(255) NOT NULL,
    exchange VARCHAR(20) NOT NULL,
    currency CHAR(3) NOT NULL DEFAULT 'INR',
    status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE',
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_instruments_exchange_symbol UNIQUE (exchange, symbol),
    CONSTRAINT chk_instruments_currency CHECK (currency ~ '^[A-Z]{3}$'),
    CONSTRAINT chk_instruments_status CHECK (status IN ('ACTIVE','SUSPENDED','DELISTED'))
);

CREATE TABLE orders (
    order_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    instrument_id BIGINT NOT NULL,
    order_type VARCHAR(10) NOT NULL,
    order_side VARCHAR(10) NOT NULL,
    quantity NUMERIC(20,6) NOT NULL,
    filled_quantity NUMERIC(20,6) NOT NULL DEFAULT 0,
    limit_price NUMERIC(20,8),
    average_execution_price NUMERIC(20,8),
    status VARCHAR(25) NOT NULL DEFAULT 'PENDING',
    brokerage_amount NUMERIC(20,2) NOT NULL DEFAULT 0,
    idempotency_key VARCHAR(100) NOT NULL UNIQUE,
    placed_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    completed_at TIMESTAMP,
    cancelled_at TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_orders_account FOREIGN KEY (account_id) REFERENCES accounts(account_id) ON DELETE RESTRICT,
    CONSTRAINT fk_orders_instrument FOREIGN KEY (instrument_id) REFERENCES instruments(instrument_id) ON DELETE RESTRICT,
    CONSTRAINT chk_orders_type CHECK (order_type IN ('MARKET','LIMIT')),
    CONSTRAINT chk_orders_side CHECK (order_side IN ('BUY','SELL')),
    CONSTRAINT chk_orders_status CHECK (status IN ('PENDING','OPEN','PARTIALLY_FILLED','FILLED','CANCELLED','REJECTED')),
    CONSTRAINT chk_orders_quantity CHECK (quantity > 0),
    CONSTRAINT chk_orders_filled CHECK (filled_quantity >= 0 AND filled_quantity <= quantity),
    CONSTRAINT chk_orders_limit_price CHECK ((order_type='MARKET' AND limit_price IS NULL) OR (order_type='LIMIT' AND limit_price > 0)),
    CONSTRAINT chk_orders_execution_price CHECK (average_execution_price IS NULL OR average_execution_price > 0),
    CONSTRAINT chk_orders_brokerage CHECK (brokerage_amount >= 0),
    CONSTRAINT chk_orders_version CHECK (version >= 0)
);
CREATE INDEX idx_orders_account_placed ON orders(account_id, placed_at DESC);
CREATE INDEX idx_orders_account_completed ON orders(account_id, completed_at DESC);

CREATE TABLE positions (
    account_id BIGINT NOT NULL,
    instrument_id BIGINT NOT NULL,
    quantity NUMERIC(20,6) NOT NULL,
    average_buy_price NUMERIC(20,8) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (account_id, instrument_id),
    CONSTRAINT fk_positions_account FOREIGN KEY (account_id) REFERENCES accounts(account_id) ON DELETE CASCADE,
    CONSTRAINT fk_positions_instrument FOREIGN KEY (instrument_id) REFERENCES instruments(instrument_id) ON DELETE RESTRICT,
    CONSTRAINT chk_positions_quantity CHECK (quantity > 0),
    CONSTRAINT chk_positions_price CHECK (average_buy_price > 0),
    CONSTRAINT chk_positions_version CHECK (version >= 0)
);

CREATE TABLE holdings (
    account_id BIGINT NOT NULL,
    instrument_id BIGINT NOT NULL,
    quantity NUMERIC(20,6) NOT NULL,
    average_buy_price NUMERIC(20,8) NOT NULL,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    version BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (account_id, instrument_id),
    CONSTRAINT fk_holdings_account FOREIGN KEY (account_id) REFERENCES accounts(account_id) ON DELETE CASCADE,
    CONSTRAINT fk_holdings_instrument FOREIGN KEY (instrument_id) REFERENCES instruments(instrument_id) ON DELETE RESTRICT,
    CONSTRAINT chk_holdings_quantity CHECK (quantity > 0),
    CONSTRAINT chk_holdings_price CHECK (average_buy_price > 0),
    CONSTRAINT chk_holdings_version CHECK (version >= 0)
);

CREATE TABLE pnl (
    pnl_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id BIGINT NOT NULL,
    instrument_id BIGINT NOT NULL,
    sell_order_id BIGINT NOT NULL,
    quantity NUMERIC(20,6) NOT NULL,
    buy_price NUMERIC(20,8) NOT NULL,
    sell_price NUMERIC(20,8) NOT NULL,
    gross_pnl NUMERIC(20,2) NOT NULL,
    brokerage NUMERIC(20,2) NOT NULL DEFAULT 0,
    net_pnl NUMERIC(20,2) NOT NULL,
    realized_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_pnl_account FOREIGN KEY (account_id) REFERENCES accounts(account_id) ON DELETE RESTRICT,
    CONSTRAINT fk_pnl_instrument FOREIGN KEY (instrument_id) REFERENCES instruments(instrument_id) ON DELETE RESTRICT,
    CONSTRAINT fk_pnl_sell_order FOREIGN KEY (sell_order_id) REFERENCES orders(order_id) ON DELETE RESTRICT,
    CONSTRAINT chk_pnl_quantity CHECK (quantity > 0),
    CONSTRAINT chk_pnl_buy_price CHECK (buy_price > 0),
    CONSTRAINT chk_pnl_sell_price CHECK (sell_price > 0),
    CONSTRAINT chk_pnl_brokerage CHECK (brokerage >= 0),
    CONSTRAINT chk_pnl_net CHECK (net_pnl = gross_pnl - brokerage)
);
CREATE INDEX idx_pnl_account_date ON pnl(account_id, realized_at DESC);

CREATE TABLE watchlists (
    watchlist_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_watchlists_user_name UNIQUE (user_id, name),
    CONSTRAINT fk_watchlists_user FOREIGN KEY (user_id) REFERENCES users(user_id) ON DELETE CASCADE,
    CONSTRAINT chk_watchlists_name CHECK (LENGTH(TRIM(name)) > 0)
);
CREATE INDEX idx_watchlists_user_id ON watchlists(user_id);

CREATE TABLE watchlist_instruments (
    watchlist_id BIGINT NOT NULL,
    instrument_id BIGINT NOT NULL,
    added_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (watchlist_id, instrument_id),
    CONSTRAINT fk_wi_watchlist FOREIGN KEY (watchlist_id) REFERENCES watchlists(watchlist_id) ON DELETE CASCADE,
    CONSTRAINT fk_wi_instrument FOREIGN KEY (instrument_id) REFERENCES instruments(instrument_id) ON DELETE RESTRICT
);
CREATE INDEX idx_wi_instrument_id ON watchlist_instruments(instrument_id);

